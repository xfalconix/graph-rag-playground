"""Store real application runs and traces in MLflow."""

import os
import subprocess
import time
from functools import lru_cache
from pathlib import Path

import mlflow
import pandas as pd

from graph_store import graph_fingerprint
from workflow import PROMPT_VERSION


@lru_cache(maxsize=1)
def source_revision() -> str:
    """Record the checked-out revision, or an explicit deployment override."""
    if os.getenv("GIT_COMMIT"):
        return os.environ["GIT_COMMIT"]
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=Path(__file__).resolve().parent,
            text=True, stderr=subprocess.DEVNULL, timeout=2,
        ).strip()
    except (OSError, subprocess.SubprocessError):
        return "local-unversioned"


def configure_tracking():
    """Use Databricks in the cloud or a persistent local SQLite file."""
    mlflow.set_tracking_uri(os.getenv("MLFLOW_TRACKING_URI", "sqlite:///mlflow.db"))
    experiment = mlflow.set_experiment(os.getenv("MLFLOW_EXPERIMENT_NAME", "graph-rag-playground"))
    mlflow.langchain.autolog()
    return experiment.experiment_id


def common_tags(session_id: str, operation: str) -> dict:
    return {
        "app": "graph-rag-playground",
        "session_id": session_id,
        "operation": operation,
        "traffic_type": os.getenv("TRAFFIC_TYPE", "demo"),
        "app_version": os.getenv("APP_VERSION", "0.1.0"),
        "prompt_version": PROMPT_VERSION,
        "model": os.getenv("GROQ_MODEL", "openai/gpt-oss-120b"),
        "git_commit": source_revision(),
    }


def save_graph_with_tracking(store, graph, session_id: str) -> str:
    """A run persists the graph size, version and actual write duration."""
    with mlflow.start_run(run_name="create_graph", tags=common_tags(session_id, "create_graph")):
        started = time.perf_counter()
        try:
            graph_id = store.save(graph)
            mlflow.set_tags({"graph_id": graph_id, "data_sha256": graph_fingerprint(graph), "result": "saved"})
            mlflow.log_metrics({"entity_count": len(graph.entities), "relation_count": len(graph.relations), "error": 0})
            return graph_id
        except Exception:
            mlflow.log_metric("error", 1)
            mlflow.set_tag("result", "error")
            raise
        finally:
            mlflow.log_metric("duration_seconds", time.perf_counter() - started)


def ask_with_tracking(workflow, question: str, graph_id: str, entities: list[dict], session_id: str) -> dict:
    """One run and one root trace for each submitted question."""
    with mlflow.start_run(run_name="ask_graph", tags=common_tags(session_id, "ask_graph")) as run:
        started = time.perf_counter()
        mlflow.set_tag("graph_id", graph_id)
        try:
            with mlflow.start_span(name="graph_question", span_type="CHAIN") as span:
                # Link the run even when the workflow fails before producing an answer.
                mlflow.set_tag("trace_id", span.trace_id)
                span.set_inputs({"question": question, "graph_id": graph_id})
                result = workflow.invoke({"question": question, "graph_id": graph_id, "entities": entities})
                span.set_outputs({"answer": result["answer"], "status": result["status"], "facts": result["facts"]})
                trace_id = span.trace_id
            mlflow.set_tags({"result": result["status"], "intent": result["plan"]["intent"], "trace_id": trace_id})
            mlflow.log_metrics({"error": 0, "fact_count": len(result["facts"]), "abstained": int(result["status"] != "answered")})
            result.update({"run_id": run.info.run_id, "trace_id": trace_id})
            return result
        except Exception as error:
            mlflow.set_tags({"result": "error", "error_type": type(error).__name__})
            mlflow.log_metric("error", 1)
            raise
        finally:
            mlflow.log_metric("duration_seconds", time.perf_counter() - started)


def read_operations(experiment_id: str, session_id: str | None = None) -> pd.DataFrame:
    """Read persisted runs; an ordinary visitor sees only their session."""
    filters = "tags.app = 'graph-rag-playground'"
    if session_id:
        # Session IDs are generated by the server, never supplied by the visitor.
        if len(session_id) != 32 or not all(character in "0123456789abcdef" for character in session_id):
            raise ValueError("Invalid session identifier.")
        filters += f" AND tags.session_id = '{session_id}'"
    return mlflow.search_runs(experiment_ids=[experiment_id], filter_string=filters,
                              order_by=["start_time DESC"], max_results=500)
